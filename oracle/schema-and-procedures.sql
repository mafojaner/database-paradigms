set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "LIBRARYDB"."REGISTER_STUDENT" (
    p_studentNo IN NUMBER,
    p_moduleCode IN VARCHAR2
) AS
    v_exists NUMBER;
BEGIN

    SELECT COUNT(*) INTO v_exists
    FROM STUDENT
    WHERE studentNo = p_studentNo;

    IF v_exists = 0 THEN
        DBMS_OUTPUT.PUT_LINE('Error: Student number ' || p_studentNo || ' does not exist.');
        RETURN;
    END IF;


    SELECT COUNT(*) INTO v_exists
    FROM MODULE
    WHERE moduleCode = p_moduleCode;

    IF v_exists = 0 THEN
        DBMS_OUTPUT.PUT_LINE('Error: Module code ' || p_moduleCode || ' does not exist.');
        RETURN;
    END IF;


    SELECT COUNT(*) INTO v_exists
    FROM REGISTRATION
    WHERE studentNo = p_studentNo
      AND moduleCode = p_moduleCode;

    IF v_exists > 0 THEN
        DBMS_OUTPUT.PUT_LINE('Warning: Student ' || p_studentNo || 
                             ' is already registered for module ' || p_moduleCode);
        RETURN;
    END IF;


    INSERT INTO REGISTRATION (moduleCode, studentNo)
    VALUES (p_moduleCode, p_studentNo);

    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Success: Student ' || p_studentNo || 
                         ' registered for module ' || p_moduleCode);

EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        DBMS_OUTPUT.PUT_LINE('Error: ' || SQLERRM);
END register_student;

